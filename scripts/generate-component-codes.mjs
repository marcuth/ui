// Generates playground/components/component-codes.generated.ts: the "Code" tab snippet of every
// preview, taken from its JSX in component-previews.tsx so code and preview never drift.
// Hand-written snippets in component-codes.ts take precedence.
import { readFileSync, writeFileSync } from "node:fs"

const source = readFileSync("playground/components/component-previews.tsx", "utf8").replaceAll("\r\n", "\n")

// name -> { module, type } for every named import of the previews file.
const owner = new Map()
for (const [, list, mod] of source.matchAll(/import (?:type )?\{([^}]*)\} from "([^"]+)"/g)) {
    for (const raw of list.split(",")) {
        const item = raw.trim()
        if (!item) continue
        const isType = item.startsWith("type ")
        owner.set(item.replace(/^type /, ""), { module: mod, type: isType })
    }
}

const previewsStart = source.indexOf("export const previews")
const header = source.slice(0, previewsStart)

// Shared fixtures (data/columns declared above the previews), as blank-line separated blocks.
const fixtureStart = header.indexOf("/* ─── Shared fixtures")
const fixtureEnd = header.indexOf("/* ─── Wrapper")
const fixtures = []
for (const block of header.slice(fixtureStart, fixtureEnd).split(/\n\n+/)) {
    const lines = block.split("\n").filter((l) => !l.startsWith("/*"))
    const code = lines.join("\n").trim()
    const declared = [...code.matchAll(/^(?:const|type) (\w+)/gm)].map((m) => m[1])
    if (code && declared.length) fixtures.push({ code, declared })
}

const word = (name) => new RegExp(String.raw`\b${name}\b`)

function dedent(text, by) {
    return text
        .split("\n")
        .map((line) => (line.startsWith(" ".repeat(by)) ? line.slice(by) : line.trimStart()))
        .join("\n")
}

const indent = (text, by) =>
    text
        .split("\n")
        .map((l) => (l ? " ".repeat(by) + l : l))
        .join("\n")

const pascal = (slug) =>
    slug
        .split("-")
        .map((p) => p[0].toUpperCase() + p.slice(1))
        .join("")

const body = source.slice(previewsStart)
const entries = [...body.matchAll(/^    ("?)([\w-]+)\1: \(\n([\s\S]*?)^    \),?$/gm)]

const out = {}
for (const [, , slug, raw] of entries) {
    let inner = raw.trimEnd().split("\n")
    // Drop the outer <PreviewWrapper> … </PreviewWrapper>.
    if (/^\s*<PreviewWrapper>/.test(inner[0]) && /<\/PreviewWrapper>\s*$/.test(inner.at(-1))) {
        inner = inner.slice(1, -1)
    }
    const jsx = dedent(inner.join("\n"), 12)

    // Fixtures used by the JSX, plus the ones those depend on.
    const used = new Set()
    let scan = jsx
    for (let changed = true; changed;) {
        changed = false
        for (const fixture of fixtures) {
            if (used.has(fixture) || !fixture.declared.some((n) => word(n).test(scan))) continue
            used.add(fixture)
            scan += "\n" + fixture.code
            changed = true
        }
    }
    const fixtureCode = fixtures.filter((f) => used.has(f)).map((f) => f.code)

    const byModule = new Map()
    for (const [name, info] of owner) {
        if (info.module === "react" || !word(name).test(scan)) continue
        const label = info.type ? `type ${name}` : name
        byModule.set(info.module, [...(byModule.get(info.module) ?? []), label])
    }
    const imports = [...byModule]
        .sort(([a], [b]) => (a === "@marcuth/ui" ? -1 : b === "@marcuth/ui" ? 1 : a.localeCompare(b)))
        .map(([mod, names]) => `import { ${[...new Set(names)].sort().join(", ")} } from "${mod}"`)
        .join("\n")

    // Several root nodes need a wrapper.
    const rootCount = jsx.split("\n").filter((l) => /^<\w/.test(l)).length
    const returned = rootCount > 1 ? `<>\n${indent(jsx, 4)}\n</>` : jsx

    out[slug] = [
        imports,
        "",
        ...(fixtureCode.length ? [fixtureCode.join("\n\n"), ""] : []),
        `export default function ${pascal(slug)}Demo() {`,
        "    return (",
        indent(returned, 8),
        "    )",
        "}",
    ].join("\n")
}

writeFileSync(
    "playground/components/component-codes.generated.ts",
    `// Generated by scripts/generate-component-codes.mjs from component-previews.tsx. Do not edit.
export const generatedCodes: Record<string, string> = ${JSON.stringify(out, null, 4)}
`,
)
console.log(`Generated ${Object.keys(out).length} snippets`)
