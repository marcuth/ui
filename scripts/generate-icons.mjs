// Generates src/icons/<slug>.ts, one file per react-icons set: `npm run icons`.
// Fails when react-icons ships a set that has no slug below, so none goes missing silently.
import { readdir, unlink, writeFile } from "node:fs/promises"
import { createRequire } from "node:module"

const { IconsManifest } = createRequire(import.meta.url)("react-icons")

/** react-icons pack id → entry point under `@marcuth/ui/icons/<slug>`. */
const slugs = {
    ai: "ant-design",
    bi: "boxicons",
    bs: "bootstrap",
    cg: "css-gg",
    ci: "circum",
    di: "devicons",
    fa: "font-awesome",
    fa6: "font-awesome-6",
    fc: "flat-color",
    fi: "feather",
    gi: "game-icons",
    go: "octicons",
    gr: "grommet",
    hi: "heroicons",
    hi2: "heroicons-2",
    im: "icomoon",
    io: "ionicons-4",
    io5: "ionicons",
    lia: "line-awesome",
    lu: "lucide",
    md: "material-design",
    pi: "phosphor",
    ri: "remix",
    rx: "radix",
    si: "simple-icons",
    sl: "simple-line",
    tb: "tabler",
    tfi: "themify",
    ti: "typicons",
    vsc: "vscode",
    wi: "weather",
}

/** Extra guidance for the sets the library leans on. */
const notes = {
    lu: "The default UI set: use it for interface icons.",
    si: "Brand logos (`SiGithub`, `SiLinkedin`…) for social links.",
}

const unmapped = IconsManifest.filter((pack) => !slugs[pack.id])
if (unmapped.length) {
    throw new Error(`Add a slug for: ${unmapped.map((pack) => `${pack.id} (${pack.name})`).join(", ")}`)
}

const prefix = (id) => id.charAt(0).toUpperCase() + id.slice(1)
const expected = new Set()

for (const pack of IconsManifest) {
    const slug = slugs[pack.id]
    const file = `${slug}.ts`
    expected.add(file)
    const lines = [
        "// Generated by scripts/generate-icons.mjs. Do not edit.",
        `/**`,
        ` * ${pack.name} (\`react-icons/${pack.id}\`, \`${prefix(pack.id)}*\`). License: ${pack.license}.`,
        ...(notes[pack.id] ? [` * ${notes[pack.id]}`] : []),
        ` * ${pack.projectUrl}`,
        ` */`,
        `export * from "react-icons/${pack.id}"`,
        "",
    ]
    await writeFile(`src/icons/${file}`, lines.join("\n"))
}

// Drop files for sets react-icons no longer ships.
for (const file of await readdir("src/icons")) {
    if (file !== "index.ts" && file.endsWith(".ts") && !expected.has(file)) await unlink(`src/icons/${file}`)
}

console.log(`Generated ${expected.size} icon sets in src/icons/.`)
